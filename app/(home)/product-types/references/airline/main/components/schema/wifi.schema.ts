import { z } from "zod";

// ======================================================
// WIFI PACKAGE
// ======================================================

export const FlyWifiPackageSchema = z.object({
  // ======================================================
  // RELATIONS
  // ======================================================

  airlineId: z.string(),

  // ======================================================
  // BASIC
  // ======================================================

  name: z.string().min(1),

  // ======================================================
  // LIMIT
  // ======================================================

  dataLimitMb: z.number().optional(),

  durationMinutes: z.number().optional(),

  // ======================================================
  // PRICE
  // ======================================================

  amount: z.number(),
});

export type FlyWifiPackageFormValues = z.infer<typeof FlyWifiPackageSchema>;
