import { z } from "zod";

// ======================================================
// ROOM MEDIA - MANAGE
// ======================================================

export const roomMediaSchema = z.object({
  // ====================================================
  // MEDIA
  // ====================================================

  mediaId: z.string(),

  // ====================================================
  // CATEGORY
  // ====================================================

  categoryId: z.string().nullable().optional(),

  // ====================================================
  // DISPLAY
  // ====================================================

  isPrimary: z.boolean().default(false),

  sortOrder: z.number().int().default(0),
});

// ======================================================
// TYPES
// ======================================================

export type RoomMediaInput = z.infer<typeof roomMediaSchema>;
